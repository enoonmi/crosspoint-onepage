#pragma once

#include <cstdint>
#include <string>
#include <vector>

namespace anx {

/** Progress record for one book, as exchanged with Anx Reader. */
struct BookProgress {
  /**
   * Book path exactly as Anx Reader stores it in `tb_books.file_path`,
   * i.e. "file/<hash>.epub" (relative to `anx/data/`). This is the join key on
   * the Anx Reader side, so it must not be rewritten into a local path.
   */
  std::string filePath;
  /** Reading position in [0.0, 1.0]. */
  double percentage = 0.0;
  /** Unix timestamp (seconds) when this position was recorded. */
  int64_t updatedAt = 0;
};

/** The `anx/onepage/progress.json` document. */
struct ProgressDocument {
  int schema = 1;
  std::string device;
  int64_t updatedAt = 0;
  std::vector<BookProgress> books;
};

/**
 * Reader / writer for `anx/onepage/progress.json`.
 *
 * Why this file exists
 * --------------------
 * Anx Reader syncs its whole SQLite database as a single file and, on the way,
 * deletes remote book files that are not in it. A device that uploaded its own
 * `database*.db` would therefore wipe the phone's notes, groups and reading
 * statistics. So the device writes progress to this separate path instead,
 * which Anx Reader ignores and `syncFiles()` does not touch, and the Anx Reader
 * side merges it in.
 *
 * Contract
 * --------
 *  - Only `reading_percentage` is transported. `tb_books.last_read_position`
 *    holds an EPUB CFI generated by foliate-js; a device without a DOM cannot
 *    produce one, and overwriting it would make the phone lose its precise
 *    position. The merge must therefore leave the CFI alone.
 *  - `file_path` is the join key and is copied verbatim.
 *  - Percentages are clamped into [0, 1] on read and write: a bug elsewhere
 *    must not push a nonsense value into the phone's database.
 *  - Unknown fields are ignored on read so a newer phone-side writer can add
 *    fields without breaking older firmware.
 *  - The writer emits a stable field order so diffs are readable.
 *
 * This module is pure C++ (no Arduino, no filesystem) so it is host-tested.
 */
class ProgressJson {
 public:
  /** Current schema version written by this implementation. */
  static constexpr int kSchemaVersion = 1;

  /** Device identifier written into the document. */
  static const char* defaultDeviceName();

  /**
   * Serialize a document to JSON text.
   * Entries are emitted in the order given; `updatedAt` is written as an
   * RFC 1123 GMT string for readability alongside a numeric `updated_at_unix`.
   */
  static std::string write(const ProgressDocument& document);

  /**
   * Parse JSON text produced by write() (or by a future Anx Reader build).
   *
   * @param json  input text
   * @param out   receives the parsed document; cleared first
   * @return false on malformed input. A syntactically valid document with no
   *         books returns true and an empty `books` vector.
   */
  static bool parse(const std::string& json, ProgressDocument& out);

  /**
   * Insert or update one book's progress.
   * An existing entry is only replaced when `entry.updatedAt` is newer, so a
   * device that wakes up with a stale cached value cannot overwrite a newer
   * position written moments earlier.
   *
   * @return true when the document was modified
   */
  static bool upsert(ProgressDocument& document, const BookProgress& entry);

  /** Find an entry by `filePath`; returns nullptr when absent. */
  static const BookProgress* find(const ProgressDocument& document, const std::string& filePath);

  /** Clamp a percentage into [0, 1]; NaN maps to 0. */
  static double clampPercentage(double value);
};

}  // namespace anx
